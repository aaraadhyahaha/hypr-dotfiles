// Renders the motion tokens (motionTokens.ts) for the two consumers that can't import TS:
// SCSS (styles/_motion.scss) and Hyprland's Lua config (hypr/conf/motion.lua).
// Pure: scripts/motion.ts writes the files, motionTokensModel.test.ts checks they're in sync.

export type Curve = readonly [number, number, number, number]
export type Tokens = {
  durations: Record<string, number>
  compositor: Record<string, number>
  curves: Record<string, Curve>
}

const SOURCE = "ags/widget/common/motionTokens.ts"
const header = (comment: string) =>
  `${comment} generated by \`npm run motion\` from ${SOURCE} — do not edit\n`

const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`)
const camelCap = (s: string) => s.charAt(0).toUpperCase() + s.slice(1)

// base is the plain $dur, standard the plain $ease; every other token gets a suffix
export const scssDur = (name: string) => (name === "base" ? "$dur" : `$dur-${kebab(name)}`)
export const scssEase = (name: string) => (name === "standard" ? "$ease" : `$ease-${kebab(name)}`)
// Hyprland curve names: standard is "ease", the rest "easeOut", "easeIn", …
export const luaCurve = (name: string) => (name === "standard" ? "ease" : `ease${camelCap(name)}`)

const num = (n: number) => {
  if (!Number.isFinite(n)) throw new Error(`motion token is not a finite number: ${n}`)
  return String(n)
}

export function renderScss(t: Tokens): string {
  const lines = [header("//")]
  for (const [name, c] of Object.entries(t.curves)) lines.push(`${scssEase(name)}: cubic-bezier(${c.map(num).join(", ")});`)
  lines.push("")
  for (const [name, ms] of Object.entries(t.durations)) lines.push(`${scssDur(name)}: ${num(ms)}ms;`)
  return lines.join("\n") + "\n"
}

export function renderLua(t: Tokens): string {
  const ms = { ...t.durations, ...t.compositor }
  const lines = [
    header("--"),
    "-- ms: durations in milliseconds (Hyprland's speed is ms / 100); curves: bezier control points",
    "return {",
    "  ms = {",
    ...Object.entries(ms).map(([k, v]) => `    ${k} = ${num(v)},`),
    "  },",
    "  curves = {",
    ...Object.entries(t.curves).map(
      ([k, [x1, y1, x2, y2]]) => `    ${luaCurve(k)} = { {${num(x1)}, ${num(y1)}}, {${num(x2)}, ${num(y2)}} },`,
    ),
    "  },",
    "}",
  ]
  return lines.join("\n") + "\n"
}
