// Size-dependent tracking for SF Pro, as CoreText applies it on macOS.
// SF Pro carries an AAT `trak` table, but Pango/HarfBuzz ignore `trak` in OpenType fonts,
// so on Linux it never applies: the generated styles/_tracking.scss restores it as letter-spacing.
// Pure: scripts/tracking.ts reads the font files and writes the SCSS, trackingModel.test.ts checks it.
// Measured on hypr/scripts/fontbench (config I), whose trak_spacing() this mirrors.

// the normal (track 0) entry of a trak table: per-em values at each point size
export type Trak = { upem: number; sizes: number[]; values: number[] }

// Parses the horizontal normal track of an sfnt's `trak` table; null when the font has none.
export function parseTrak(bytes: Uint8Array): Trak | null {
  const v = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength)
  const tables = new Map<string, number>()
  for (let i = 0; i < v.getUint16(4); i++) {
    const rec = 12 + 16 * i
    const tag = String.fromCharCode(...bytes.subarray(rec, rec + 4))
    tables.set(tag, v.getUint32(rec + 8))
  }
  const head = tables.get("head")
  const o = tables.get("trak")
  if (head === undefined || o === undefined) return null
  const upem = v.getUint16(head + 18)
  const horiz = v.getUint16(o + 6)
  if (horiz === 0) return null
  const h = o + horiz
  const nTracks = v.getUint16(h)
  const nSizes = v.getUint16(h + 2)
  const sizeOff = v.getUint32(h + 4)
  const sizes = Array.from({ length: nSizes }, (_, i) => v.getInt32(o + sizeOff + 4 * i) / 65536)
  for (let i = 0; i < nTracks; i++) {
    const entry = h + 8 + 8 * i
    if (v.getInt32(entry) !== 0) continue
    const off = v.getUint16(entry + 6)
    const values = Array.from({ length: nSizes }, (_, j) => v.getInt16(o + off + 2 * j))
    return { upem, sizes, values }
  }
  return null
}

// Letter-spacing in px at px size: linear between the table's sizes, clamped at its ends.
export function trackAt(t: Trak, px: number): number {
  const { sizes, values } = t
  let units: number
  if (px <= sizes[0]) units = values[0]
  else if (px >= sizes[sizes.length - 1]) units = values[values.length - 1]
  else {
    const j = sizes.findIndex((s) => s >= px)
    const f = (px - sizes[j - 1]) / (sizes[j] - sizes[j - 1])
    units = values[j - 1] + f * (values[j] - values[j - 1])
  }
  return (units / t.upem) * px
}

// the sizes the SCSS maps cover; text-size() rounds to the nearest whole px
export const SIZES = { from: 6, to: 64 }

const px = (n: number) => {
  const r = Math.round(n * 1000) / 1000
  return `${Object.is(r, -0) ? 0 : r}px`
}

function map(name: string, t: Trak): string[] {
  const rows = [`$${name}: (`]
  for (let s = SIZES.from; s <= SIZES.to; s++) rows.push(`  ${s}: ${px(trackAt(t, s))},`)
  rows.push(");")
  return rows
}

// $tracking-text / $tracking-display: whole px size → letter-spacing
export function renderScss(cuts: { text: Trak; display: Trak }): string {
  return [
    "// generated by `npm run tracking` from the SF Pro trak tables — do not edit",
    "// size (px) → letter-spacing, read by @include text-size() in _mixins.scss",
    "",
    ...map("tracking-text", cuts.text),
    "",
    ...map("tracking-display", cuts.display),
    "",
  ].join("\n")
}
